// LANGUAGE SELECTOR
// ============================================================

document.addEventListener(
    "DOMContentLoaded",
    function () {


        const languageSelect =
            document.getElementById(
                "languageSelect"
            );


        if (!languageSelect) {
            return;
        }


        // Get previously selected language

        const savedLanguage =
            localStorage.getItem(
                "selectedLanguage"
            ) || "en";


        languageSelect.value =
            savedLanguage;



        // Apply saved language

        if (savedLanguage !== "en") {

            translatePage(
                savedLanguage
            );

        }



        // Change language

        languageSelect.addEventListener(
            "change",
            function () {

                const selectedLanguage =
                    this.value;


                // Reload page before translating
                // so English original text is restored

                localStorage.setItem(
                    "selectedLanguage",
                    selectedLanguage
                );


                location.reload();

            }
        );

    }
);