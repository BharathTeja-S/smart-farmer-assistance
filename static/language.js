// TRANSLATION FUNCTION
// ============================================================

function translatePage(language) {

    if (!translations[language]) {
        language = "en";
    }


    // --------------------------------------------------------
    // Translate every text node on the page
    // --------------------------------------------------------

    const walker =
        document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT
        );


    const textNodes = [];


    let node;


    while (node = walker.nextNode()) {

        textNodes.push(node);

    }


    textNodes.forEach(function (textNode) {

        const original =
            textNode.nodeValue;

        const cleanText =
            original.trim();


        if (!cleanText) {
            return;
        }


        if (
            translations[language] &&
            translations[language][cleanText]
        ) {

            const translated =
                translations[language][cleanText];


            // Preserve spaces around text

            const startSpaces =
                original.match(/^\s*/)[0];

            const endSpaces =
                original.match(/\s*$/)[0];


            textNode.nodeValue =
                startSpaces +
                translated +
                endSpaces;

        }

    });


    // --------------------------------------------------------
    // Translate SELECT options
    // --------------------------------------------------------

    document
        .querySelectorAll("option")
        .forEach(function (option) {

            const text =
                option.textContent.trim();


            if (
                translations[language] &&
                translations[language][text]
            ) {

                option.textContent =
                    translations[language][text];

            }

        });


    // --------------------------------------------------------
    // Translate placeholders
    // --------------------------------------------------------

    document
        .querySelectorAll("input[placeholder]")
        .forEach(function (input) {

            const placeholder =
                input.getAttribute("placeholder");


            if (
                translations[language] &&
                translations[language][placeholder]
            ) {

                input.setAttribute(
                    "placeholder",
                    translations[language][placeholder]
                );

            }

        });


    // --------------------------------------------------------
    // Save selected language
    // --------------------------------------------------------

    localStorage.setItem(
        "selectedLanguage",
        language
    );



    // --------------------------------------------------------
    // Keep HTML language attribute correct
    // --------------------------------------------------------

    document.documentElement.lang =
        language;

}



